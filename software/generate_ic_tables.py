"""
Offline export step: digital twin -> JSON tables + C headers.

For each of the 6 target ICs, runs the digital twin's exhaustive fault
simulation + greedy set-cover compaction ONCE, then emits two artifacts from
that SAME in-memory result:

  software/tables/<IC_NAME>.json                  -- consumed by pc_tester.py
  firmware/Core/Inc/ic_table_<IC_NAME>.h          -- consumed by firmware
                                                     (see HEADER_OUT_DIRS)

Also writes software/tables/compaction_stats.json, the headline
per-IC (exhaustive, compacted, aliased) numbers for the paper's Results
section.

Run this once whenever digital_twin.py's logic changes; commit the generated
files -- firmware and pc_tester.py never recompute a fault dictionary
themselves. The digital twin itself (digital_twin.py) has no board-specific
code at all -- it models IC logic/faults only -- so porting to a new board
never requires touching it. The one thing
that DOES need updating per new board port is HEADER_OUT_DIRS below, so the
generated ic_table_*.h land in that board's Core/Inc too.
"""
import json
import os

from digital_twin import IC_CLASSES

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
JSON_OUT_DIR = os.path.join(SCRIPT_DIR, "tables")

# One entry per board port that ships its own Core/Inc/ic_table_*.h copy.
# Add a new line here if another board port is added -- nothing else in this
# script needs to change.
HEADER_OUT_DIRS = [
    os.path.join(PROJECT_ROOT, "firmware", "Core", "Inc"),    # NUCLEO-F446RE STM32CubeIDE project
]


def c_string_literal(s):
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def build_fault_rows(fault_dictionary, gate_map):
    """[(signature, fault_name, display_string), ...], stable sorted order."""
    rows = []
    for signature in sorted(fault_dictionary.keys()):
        for fault_name in fault_dictionary[signature]:
            display = gate_map[fault_name]
            rows.append((signature, fault_name, display))
    return rows


def write_json(ic, vectors, fault_dictionary, gate_map):
    os.makedirs(JSON_OUT_DIR, exist_ok=True)
    path = os.path.join(JSON_OUT_DIR, f"{ic.name}.json")
    data = {
        "pin_config": ic.config_string(),
        "vectors": vectors,
        "fault_dictionary": fault_dictionary,
        "gate_map": gate_map,
    }
    with open(path, "w") as f:
        json.dump(data, f, indent=2, sort_keys=True)
    return path


def write_common_header():
    """IcFaultEntry is identical across all 6 ICs -- declare it exactly once
    here instead of repeating the typedef in every per-IC header. Written to
    EVERY board port in HEADER_OUT_DIRS -- each board keeps its own on-disk
    copy (no shared/symlinked header), so every board's Core/Inc is portable
    and buildable on its own."""
    lines = [
        "/* Auto-generated by software/generate_ic_tables.py -- DO NOT EDIT BY HAND. */",
        "#ifndef IC_TABLE_COMMON_H",
        "#define IC_TABLE_COMMON_H",
        "",
        "/* signature -> fault_name -> 16-char-max LCD display_string.",
        "   More than one row can share a signature (aliased faults) --",
        "   firmware cycles the display between all matching rows. */",
        "typedef struct {",
        "    const char* signature;",
        "    const char* fault_name;",
        "    const char* display_string;",
        "} IcFaultEntry;",
        "",
        "#endif /* IC_TABLE_COMMON_H */",
        "",
    ]
    paths = []
    for out_dir in HEADER_OUT_DIRS:
        os.makedirs(out_dir, exist_ok=True)
        path = os.path.join(out_dir, "ic_table_common.h")
        with open(path, "w") as f:
            f.write("\n".join(lines))
        paths.append(path)
    return paths


def golden_table(ic):
    """Fault-free response to EVERY exhaustive input vector, as one byte per
    vector (bit k = k-th output pin in pin_config order). Vector index i is
    the exhaustive vector whose first input char is the MSB of i -- the same
    order as ic.exhaustive_test_vectors(). Lets the firmware run the full
    golden-run check on its own, with no PC attached."""
    good = ic._response_matrix()["Good"]
    table = []
    for v in ic.exhaustive_test_vectors():
        out = good[v]
        mask = 0
        for k, c in enumerate(out):
            if c == "1":
                mask |= (1 << k)
        table.append(mask)
    return table


def write_header(ic, vectors, rows):
    ic_name = ic.name
    guard = f"IC_TABLE_{ic_name}_H"
    upper = ic_name.upper()

    lines = []
    lines.append(f"/* Auto-generated by software/generate_ic_tables.py -- DO NOT EDIT BY HAND. */")
    lines.append(f"/* Source of truth: software/digital_twin.py ({ic_name}). Regenerate, don't patch. */")
    lines.append(f"#ifndef {guard}")
    lines.append(f"#define {guard}")
    lines.append("")
    lines.append('#include "ic_table_common.h"')
    lines.append("")
    lines.append(f'#define IC_{upper}_NAME {c_string_literal(ic_name)}')
    lines.append(f'#define IC_{upper}_PIN_CONFIG {c_string_literal(ic.config_string())}')
    lines.append(f"#define IC_{upper}_NUM_VECTORS {len(vectors)}")
    lines.append(f"#define IC_{upper}_NUM_FAULT_ENTRIES {len(rows)}")
    lines.append("")
    lines.append(f"static const char* IC_{upper}_VECTORS[IC_{upper}_NUM_VECTORS] = {{")
    lines.append("    " + ", ".join(c_string_literal(v) for v in vectors) + ",")
    lines.append("};")
    lines.append("")
    golden = golden_table(ic)
    lines.append(f"/* Exhaustive golden (fault-free) responses: index = input vector (first input = MSB),")
    lines.append(f"   value bit k = expected level of the k-th 'O' pin. Used by the on-board full test. */")
    lines.append(f"#define IC_{upper}_NUM_INPUTS {len(ic.input_pins)}")
    lines.append(f"#define IC_{upper}_NUM_OUTPUTS {len(ic.output_pins)}")
    lines.append(f"#define IC_{upper}_NUM_GOLDEN {len(golden)}")
    lines.append(f"static const unsigned char IC_{upper}_GOLDEN[IC_{upper}_NUM_GOLDEN] = {{")
    for i in range(0, len(golden), 16):
        lines.append("    " + ", ".join(f"0x{g:02X}" for g in golden[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append(f"static const IcFaultEntry IC_{upper}_FAULT_TABLE[IC_{upper}_NUM_FAULT_ENTRIES] = {{")
    for sig, fault_name, display in rows:
        lines.append(
            "    {" + f"{c_string_literal(sig)}, {c_string_literal(fault_name)}, {c_string_literal(display)}" + "},"
        )
    lines.append("};")
    lines.append("")
    lines.append(f"#endif /* {guard} */")
    lines.append("")
    text = "\n".join(lines)

    paths = []
    for out_dir in HEADER_OUT_DIRS:
        os.makedirs(out_dir, exist_ok=True)
        path = os.path.join(out_dir, f"ic_table_{ic_name}.h")
        with open(path, "w") as f:
            f.write(text)
        paths.append(path)
    return paths


def main():
    stats = {}
    common_paths = write_common_header()
    for p in common_paths:
        print(f"Wrote {os.path.relpath(p, PROJECT_ROOT)}")
    print(f"{'IC':<10} {'exhaustive':>10} {'compacted':>10} {'aliased groups':>15}")
    print("-" * 50)

    for index, cls in enumerate(IC_CLASSES):
        ic = cls()

        vectors = ic.compacted_test_vectors()
        fault_dictionary = ic.fault_dictionary()
        gate_map = ic.gate_map()
        exhaustive_len, compacted_len, aliased = ic.compaction_stats()

        json_path = write_json(ic, vectors, fault_dictionary, gate_map)
        rows = build_fault_rows(fault_dictionary, gate_map)
        header_paths = write_header(ic, vectors, rows)

        stats[ic.name] = {
            "index": index,
            "exhaustive_vectors": exhaustive_len,
            "compacted_vectors": compacted_len,
            "aliased_fault_groups": aliased,
            "json": os.path.relpath(json_path, PROJECT_ROOT),
            "headers": [os.path.relpath(p, PROJECT_ROOT) for p in header_paths],
        }

        print(f"{ic.name:<10} {exhaustive_len:>10} {compacted_len:>10} {aliased:>15}")

    stats_path = os.path.join(JSON_OUT_DIR, "compaction_stats.json")
    with open(stats_path, "w") as f:
        json.dump(stats, f, indent=2, sort_keys=True)
    print(f"\nWrote per-IC stats to {os.path.relpath(stats_path, PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
